import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const packagePath = join(packageRoot, 'package.json');
const generatedPath = join(packageRoot, 'src', 'package-version.ts');
const version = JSON.parse(readFileSync(packagePath, 'utf8')).version;
const generated = `// Generated by scripts/sync-package-version.mjs during every SDK build.\nexport const RELAYFILE_VERSION = ${JSON.stringify(version)};\n`;

if (readFileSync(generatedPath, 'utf8') !== generated) {
  writeFileSync(generatedPath, generated, 'utf8');
}
